import Image from "next/image";
import Link from "next/link";
import { cn } from "@/lib/utils";

/**
 * The original MIDIS logo, used unmodified in geometry.
 *
 * Three lockups, each with a surface it belongs on:
 *   "icon"     circular black mark with the white 'm' and orange cut —
 *              self-contained, so it sits correctly on LIGHT surfaces.
 *   "wordmark" full "midis" wordmark in white with orange accents —
 *              the supplied artwork, for DARK surfaces.
 *   "lockup"   the circular mark followed by the wordmark in brand
 *              charcoal, for LIGHT surfaces. The wordmark it uses is
 *              derived, not supplied: see below.
 *
 * Nothing is redrawn or reproportioned. The one colour change in the set is
 * `wordmark-on-light.png`, generated by scripts/prepare-brand-assets.mjs:
 * MIDIS supplied the wordmark as white-on-transparent only, which is
 * invisible on this site's light header, so the white ink is mapped to the
 * brand charcoal while the orange accents come through bit-identical. That
 * was a deliberate decision — the official dark version is still outstanding
 * at item 16 of docs/02-evidence-intake.md, and when it arrives it should
 * replace the derived file rather than sit alongside it.
 */
export function Logo({
  variant = "icon",
  className,
  priority = false,
}: {
  variant?: "icon" | "wordmark" | "lockup";
  className?: string;
  priority?: boolean;
}) {
  if (variant === "lockup") {
    return (
      <span className={cn("inline-flex items-center gap-2.5 sm:gap-3", className)}>
        <Image
          src="/brand/icon-512.png"
          alt=""
          width={512}
          height={512}
          priority={priority}
          className="h-9 w-9 shrink-0 sm:h-10 sm:w-10"
        />
        <Image
          src="/brand/wordmark-on-light.png"
          alt="MIDIS"
          width={960}
          height={303}
          priority={priority}
          className="h-[1.1rem] w-auto sm:h-[1.3rem]"
        />
      </span>
    );
  }

  if (variant === "wordmark") {
    return (
      <Image
        src="/brand/wordmark-on-dark.png"
        alt="MIDIS"
        width={960}
        height={303}
        priority={priority}
        className={cn("h-8 w-auto", className)}
      />
    );
  }

  return (
    <Image
      src="/brand/icon-512.png"
      alt="MIDIS"
      width={512}
      height={512}
      priority={priority}
      className={cn("h-10 w-10", className)}
    />
  );
}

export function LogoLink({
  variant = "icon",
  className,
  priority = false,
}: {
  variant?: "icon" | "wordmark" | "lockup";
  className?: string;
  priority?: boolean;
}) {
  return (
    <Link
      href="/"
      aria-label="MIDIS — home"
      className={cn("inline-flex items-center rounded-full", className)}
    >
      <Logo variant={variant} priority={priority} />
    </Link>
  );
}
